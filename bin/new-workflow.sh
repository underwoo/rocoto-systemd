#!/usr/bin/env bash
#
# new-workflow.sh -- interactively register a Rocoto workflow instance.
#
# Always writes:
#   ~/.config/rocoto-systemd/<instance>.env         (systemd EnvironmentFile)
# Optionally writes (if you ask for a scron watchdog):
#   ~/.config/rocoto-systemd/<instance>.scrontab    (paste into `scrontab -e`)
#
# Node isolation, if chosen, is enforced in every entry point:
#   PIN_NODE= in the .env       -> node-guard.sh (ExecCondition) + loop.sh
#   #SCRON --nodelist=/PIN_NODE= -> watchdog.sh (if the scron path is used)

set -u

# cron, scron and `docker exec` can start a script with USER unset; under
# `set -u` the first bare $USER would abort it.
USER="${USER:-$(id -un)}"

DEST="${HOME}/rocoto-systemd"
ENVDIR="${HOME}/.config/rocoto-systemd"
mkdir -p "$ENVDIR"

ask() {  # ask VAR "prompt" "default"
  local __v="$1" __p="$2" __d="${3:-}" __a
  if [ -n "$__d" ]; then
    read -r -p "$__p [$__d]: " __a || true
    __a="${__a:-$__d}"
  else
    read -r -p "$__p: " __a || true
  fi
  printf -v "$__v" '%s' "$__a"
}
yesno() {  # yesno "prompt" "Y|N"  -> 0 for yes
  local __p="$1" __d="${2:-N}" __a
  read -r -p "$__p ($([ "$__d" = Y ] && echo 'Y/n' || echo 'y/N')): " __a || true
  __a="${__a:-$__d}"
  case "$__a" in [Yy]*) return 0;; *) return 1;; esac
}

echo "=== Register a Rocoto workflow instance ==="
echo

ask WF "Workflow XML path"
[ -f "$WF" ] || { echo "  ! not found: $WF" >&2; yesno "Continue anyway?" N || exit 1; }
ask WD "Working directory (cd here before rocotorun)" "$(dirname "$WF")"
[ -d "$WD" ] || { echo "  ! not a directory: $WD" >&2; yesno "Continue anyway?" N || exit 1; }
ask DB "Workflow database path" "${WD}/$(basename "${WF%.xml}").db"
ask INSTANCE "Short instance nickname" "$(basename "$WD")"

echo
echo "--- rocoto discovery ---"
ask ROCOTO_MODULEPATH "module use PATH (blank if rocoto already on PATH)" "${ROCOTO_MODULEPATH:-}"
ask ROCOTO_MODULE     "module name"                                       "${ROCOTO_MODULE:-rocoto}"
ask ROCOTO_BIN        "OR explicit bin dir (overrides module; blank = use module)" "${ROCOTO_BIN:-}"

# --- node isolation ------------------------------------------------------
echo
echo "--- node isolation ---"
echo "  Pin this instance if it will run unattended and more than one node could"
echo "  host it (each node has its own systemd --user manager; on Gaea they cannot"
echo "  talk to each other)."
PIN_NODE=""
if yesno "Pin this instance to a single node?" N; then
  ask PIN_PARTITION "partition to list nodes from (blank to skip listing)" "cron_c6"
  if [ -n "$PIN_PARTITION" ] && command -v sinfo >/dev/null 2>&1; then
    nodes="$(sinfo -h -p "$PIN_PARTITION" -N -o '%N' 2>/dev/null | sort -u | paste -sd' ' -)"
    [ -n "$nodes" ] && echo "  nodes in '$PIN_PARTITION': $nodes"
    def_node="${nodes%% *}"
  fi
  ask PIN_NODE "Node to pin to" "${def_node:-}"
fi

# --- behaviour tunables ------------------------------------------------
echo
ask VERBOSITY   "rocotorun -v level"                         "10"
ask INTERVAL    "seconds between rocotorun passes"           "300"
ask MAX_RUNTIME "loop.sh MAX_RUNTIME seconds (soft backstop)" "259200"

# --- write env file --------------------------------------------------
ENVFILE="${ENVDIR}/${INSTANCE}.env"
{
  echo "# generated by new-workflow.sh $(date)"
  echo "WF=$WF"
  echo "DB=$DB"
  echo "WD=$WD"
  echo "INSTANCE=$INSTANCE"
  [ -n "$ROCOTO_MODULEPATH" ] && echo "ROCOTO_MODULEPATH=$ROCOTO_MODULEPATH"
  [ -n "$ROCOTO_MODULE" ]     && echo "ROCOTO_MODULE=$ROCOTO_MODULE"
  [ -n "$ROCOTO_BIN" ]        && echo "ROCOTO_BIN=$ROCOTO_BIN"
  [ -n "$PIN_NODE" ]          && echo "PIN_NODE=$PIN_NODE"
  echo "VERBOSITY=$VERBOSITY"
  echo "INTERVAL=$INTERVAL"
  echo "MAX_RUNTIME=$MAX_RUNTIME"
} > "$ENVFILE"
mkdir -p "${WD}/logs" 2>/dev/null || true
echo
echo "wrote $ENVFILE"

# --- optional scron watchdog ---------------------------------------
CRONTAB_FILE=""
if yesno "Also generate a scron watchdog entry (restart if the user manager dies)?" N; then
  echo
  echo "--- scron watchdog job ---"
  ask PARTITION "scron partition" "${PIN_PARTITION:-cron_c6}"
  ask ACCOUNT   "account"          "${SLURM_ACCOUNT:-}"
  ask CRONEXPR  "cron schedule"    "*/5 * * * *"
  ask WD_MEM    "watchdog --mem"   "2G"
  ask WD_TIME   "watchdog --time"  "00:03:00"

  EXPORT="WF=$WF,DB=$DB,WD=$WD,INSTANCE=$INSTANCE"
  [ -n "$PIN_NODE" ]          && EXPORT="$EXPORT,PIN_NODE=$PIN_NODE"
  [ -n "$ROCOTO_MODULEPATH" ] && EXPORT="$EXPORT,ROCOTO_MODULEPATH=$ROCOTO_MODULEPATH"
  [ -n "$ROCOTO_MODULE" ]     && EXPORT="$EXPORT,ROCOTO_MODULE=$ROCOTO_MODULE"
  [ -n "$ROCOTO_BIN" ]        && EXPORT="$EXPORT,ROCOTO_BIN=$ROCOTO_BIN"
  EXPORT="$EXPORT,VERBOSITY=$VERBOSITY,INTERVAL=$INTERVAL,MAX_RUNTIME=$MAX_RUNTIME"

  CRONTAB_FILE="${ENVDIR}/${INSTANCE}.scrontab"
  {
    echo "#SCRON --partition=$PARTITION"
    [ -n "$ACCOUNT" ] && echo "#SCRON --account=$ACCOUNT"
    echo "#SCRON --time=$WD_TIME"
    echo "#SCRON --mem=$WD_MEM"
    echo "#SCRON --job-name=rocoto_wd_${INSTANCE}"
    echo "#SCRON --dependency=singleton"
    [ -n "$PIN_NODE" ] && echo "#SCRON --nodelist=$PIN_NODE"
    echo "#SCRON --export=$EXPORT"
    echo "#SCRON --output=${WD}/logs/watchdog_${INSTANCE}.out"
    echo
    echo "$CRONEXPR ${DEST}/watchdog.sh"
  } > "$CRONTAB_FILE"
  echo "wrote $CRONTAB_FILE"
fi

# --- next steps ----------------------------------------------------
cat <<EOF

Next  (instance: ${INSTANCE}${PIN_NODE:+, pinned to ${PIN_NODE}})
----
Run once (no scheduler, does not survive reboot):
    systemctl --user start rocoto-workflow@${INSTANCE}

Survive reboots (recommended; needs 'loginctl enable-linger $USER'):
    systemctl --user enable --now rocoto-workflow@${INSTANCE}
    # loop.sh disables it again once the workflow finishes

Watch:
    tail -f ${DEST}/logs/${INSTANCE}.service.log
    tail -f ${DEST}/logs/${INSTANCE}.mem.log
EOF

# `if`, not `[ ] &&`: this is the last command in the script, and a false test
# would make a perfectly successful registration exit 1.
if [ -n "$CRONTAB_FILE" ]; then
  cat <<EOF

Optional scron watchdog:
    scrontab -e        # paste the contents of $CRONTAB_FILE
    scrontab -l
EOF
fi
